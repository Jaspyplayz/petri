import { describe, expect, it } from "vitest";
import { featureManifests } from "@/features/registry";
import { defineFeature, type FeatureManifest } from "@/shared/lib/feature-manifest";
import { headingAnchor, renderFeatureMap } from "./render";

const plant = defineFeature({
  id: "plant",
  title: "Plant",
  summary: "A plant you can water.",
  routes: ["/garden"],
  uiLocation: "The /garden page | left column",
  howToReach: ["Open /", "Click 'Garden' in the top navigation"],
  keyboardShortcuts: [{ keys: "w", description: "waters the plant" }],
  selectors: { pot: "plant-pot", water: "plant-water-button" },
  flows: {
    water: {
      description: "Watering the plant counts it.",
      steps: [
        { action: "goto", path: "/garden" },
        { action: "fill", target: "pot", value: "soil" },
        { action: "press", target: "pot", key: "Enter" },
        { action: "click", target: "water" },
        { action: "expectText", target: "pot", text: "1" },
        { action: "expectVisible", target: "water" },
        { action: "wait", ms: 100 },
        { action: "screenshot", name: "watered" },
      ],
    },
  },
  dataTables: ["plants"],
  owners: "agents",
  riskLevel: "low",
});

const tracker = defineFeature({
  id: "tracker",
  title: 'The "tracker"',
  summary: "Counts visits.",
  routes: [],
  uiLocation: "Invisible.",
  howToReach: ["Open any page"],
  keyboardShortcuts: [],
  selectors: {},
  flows: {},
  dataTables: [],
  owners: "agents",
  riskLevel: "medium",
});

describe("renderFeatureMap", () => {
  it("renders the overview table, the page layout and one section per feature", () => {
    expect(renderFeatureMap([plant, tracker])).toBe(
      [
        "# Feature map",
        "",
        "<!-- Generated by `pnpm featuremap` from each src/features/*/feature.manifest.ts. Don't edit it by hand: CI fails when it's out of date. -->",
        "",
        "Read this before any task. It maps what's on screen to a feature folder, its `data-testid` selectors and the flows that `pnpm verify:flow <feature>.<flow>` runs.",
        "",
        "## Features",
        "",
        "| Feature | Routes | Where it is on screen | How to reach it | Selectors (`data-testid`) | Flows | Risk |",
        "|---|---|---|---|---|---|---|",
        "| [Plant (`plant`)](#plant-plant) | `/garden` | The /garden page \\| left column | Open / → Click 'Garden' in the top navigation | `plant-pot`, `plant-water-button` | `plant.water` | low |",
        '| [The "tracker" (`tracker`)](#the-tracker-tracker) | none | Invisible. | Open any page | none | none | medium |',
        "",
        "## Page layout",
        "",
        "```mermaid",
        "flowchart TB",
        '  nav["Top navigation (every page)"]',
        '  subgraph page_0["/garden"]',
        '    feature_plant["Plant (plant)"]',
        "  end",
        "  nav --> page_0",
        '  subgraph unrouted["No page of its own"]',
        '    feature_tracker["The #quot;tracker#quot; (tracker)"]',
        "  end",
        "```",
        "",
        "## Plant (`plant`)",
        "",
        "A plant you can water.",
        "",
        "- **Folder:** `src/features/plant/`",
        "- **Routes:** `/garden`",
        "- **Where it is on screen:** The /garden page | left column",
        "- **Keyboard shortcuts:** `w` waters the plant",
        "- **Data tables:** `plants`",
        "- **Risk level:** low",
        "",
        "How to reach it:",
        "",
        "1. Open /",
        "2. Click 'Garden' in the top navigation",
        "",
        "| Selector | `data-testid` |",
        "|---|---|",
        "| pot | `plant-pot` |",
        "| water | `plant-water-button` |",
        "",
        "### `plant.water`",
        "",
        "Watering the plant counts it. Run it with `pnpm verify:flow plant.water`.",
        "",
        "1. goto `/garden`",
        '2. fill `pot` with "soil"',
        "3. press Enter in `pot`",
        "4. click `water`",
        '5. expectText `pot` contains "1"',
        "6. expectVisible `water`",
        "7. wait 100 ms",
        '8. screenshot "watered"',
        "",
        '## The "tracker" (`tracker`)',
        "",
        "Counts visits.",
        "",
        "- **Folder:** `src/features/tracker/`",
        "- **Routes:** none (it has no page of its own)",
        "- **Where it is on screen:** Invisible.",
        "- **Keyboard shortcuts:** none",
        "- **Data tables:** none",
        "- **Risk level:** medium",
        "",
        "How to reach it:",
        "",
        "1. Open any page",
        "",
        "No selectors.",
        "",
        "No flows.",
        "",
      ].join("\n"),
    );
  });

  it("puts / first, then the other routes alphabetically, and shows a feature on every route it has", () => {
    const shared: FeatureManifest = { ...tracker, id: "banner", title: "Banner", routes: ["/zoo", "/"] };
    const layout = renderFeatureMap([plant, shared]).split("```mermaid")[1] ?? "";
    expect(layout.match(/subgraph page_\d+\["[^"]+"\]/g)).toEqual(['subgraph page_0["/"]', 'subgraph page_1["/garden"]', 'subgraph page_2["/zoo"]']);
    expect(layout.match(/feature_banner\[/g)).toHaveLength(2);
    expect(layout).not.toContain("unrouted");
  });

  it("renders the real manifests the same way every time", () => {
    const first = renderFeatureMap(featureManifests);
    expect(renderFeatureMap(featureManifests)).toBe(first);
    for (const manifest of featureManifests) expect(first).toContain(`## ${manifest.title} (\`${manifest.id}\`)`);
  });
});

describe("headingAnchor", () => {
  it.each([
    ["Feedback board (`feedback`)", "feedback-board-feedback"],
    ['The "tracker" (`tracker`)', "the-tracker-tracker"],
    ["Blob (`blob`)", "blob-blob"],
  ])("turns %j into GitHub's anchor %j", (heading, anchor) => {
    expect(headingAnchor(heading)).toBe(anchor);
  });
});
