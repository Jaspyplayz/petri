import { spawnSync } from "node:child_process";
import { appendFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { commandFor, describeAction, envSetupTemplate, parseEnvFile, planSetup, type SetupAction } from "./setup-secrets/plan";

const root = join(import.meta.dirname, "..");
const envSetupPath = join(root, ".env.setup");
const templatePath = join(root, ".env.setup.example");
const vercelProjectPath = join(root, ".vercel", "project.json");
const isWindows = process.platform === "win32";

function out(line: string): void {
  process.stdout.write(`${line}\n`);
}

function run(command: string, args: readonly string[], input?: string): { ok: boolean; stderr: string } {
  const result = spawnSync(command, args, {
    cwd: root,
    input: input ?? "",
    encoding: "utf8",
    shell: isWindows && command === "vercel",
    stdio: ["pipe", "pipe", "pipe"],
  });
  return { ok: result.status === 0, stderr: result.stderr.trim() };
}

function readVercelIds(): Map<string, string> {
  const ids = new Map<string, string>();
  if (!existsSync(vercelProjectPath)) return ids;
  const parsed: unknown = JSON.parse(readFileSync(vercelProjectPath, "utf8"));
  if (typeof parsed === "object" && parsed !== null) {
    const { orgId, projectId } = parsed as { orgId?: unknown; projectId?: unknown };
    if (typeof orgId === "string") ids.set("VERCEL_ORG_ID", orgId);
    if (typeof projectId === "string") ids.set("VERCEL_PROJECT_ID", projectId);
  }
  return ids;
}

function apply(action: SetupAction): boolean {
  const { command, args, stdin } = commandFor(action);
  return run(command, args, stdin).ok;
}

function main(): void {
  const { values: flags } = parseArgs({
    options: {
      apply: { type: "boolean", default: false },
      "write-template": { type: "boolean", default: false },
    },
  });

  if (flags["write-template"]) {
    writeFileSync(templatePath, envSetupTemplate());
    out(`wrote ${templatePath}`);
    return;
  }

  if (!existsSync(envSetupPath)) {
    out("No .env.setup found. Copy .env.setup.example to .env.setup, fill it in, and run again.");
    process.exit(1);
  }

  const values = parseEnvFile(readFileSync(envSetupPath, "utf8"));
  for (const [key, value] of readVercelIds()) if (!values.get(key)) values.set(key, value);

  const plan = planSetup(values);
  if (plan.missingRequired.length > 0) {
    out("Missing required values in .env.setup:");
    for (const spec of plan.missingRequired) out(`  ${spec.key}: ${spec.how}`);
    process.exit(1);
  }

  out(flags.apply ? "Applying:" : "Dry run (pass --apply to push). Would set:");
  for (const action of plan.actions) out(`  ${describeAction(action)}`);
  for (const spec of plan.skippedOptional) out(`  skipped (blank, optional) ${spec.key}`);
  if (!flags.apply) return;

  if (plan.generated.size > 0) {
    const lines = [...plan.generated].map(([key, value]) => `${key}=${value}`).join("\n");
    appendFileSync(envSetupPath, `\n# generated by pnpm setup:secrets\n${lines}\n`);
    out(`  generated ${[...plan.generated.keys()].join(", ")} and saved it to .env.setup`);
  }

  const failures = plan.actions.filter((action) => !apply(action));

  if (!run("gh", ["variable", "get", "EVOLUTION_ENABLED"]).ok) {
    run("gh", ["variable", "set", "EVOLUTION_ENABLED"], "false");
    out("  GitHub variable  EVOLUTION_ENABLED=false (the loop stays off until go-live)");
  }

  if (failures.length > 0) {
    out("Failed (values were not printed):");
    for (const action of failures) out(`  ${describeAction(action)}`);
    process.exit(1);
  }
  out(`Done: ${String(plan.actions.length)} values pushed.`);
}

main();
